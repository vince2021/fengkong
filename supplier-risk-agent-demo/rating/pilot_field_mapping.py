def build_pilot_field_mapping_package(template_key: str, model_config: dict) -> dict:
    industry_label = preferred_industry_label(template_key)
    model_version = model_config.get("version", "-")
    weights = model_config.get("weights", {})
    strong_rules = model_config.get("strong_rules", [])
    enabled_strong_rules = [rule for rule in strong_rules if rule.get("enabled", True)]
    dominant_dimensions = _dominant_dimensions(weights)
    readiness_checklist = _build_data_readiness_checklist(industry_label, model_version)

    package = {
        "package_title": f"{industry_label}试点字段映射包",
        "industry_label": industry_label,
        "model_name": model_config.get("name", "客商信用评级模型"),
        "model_version": model_version,
        "summary": {
            "行业模板": industry_label,
            "模型名称": model_config.get("name", "客商信用评级模型"),
            "模型版本": model_version,
            "强规则数量": f"{len(enabled_strong_rules)} 条",
            "核心权重维度": dominant_dimensions,
            "准备清单字段": f"{len(readiness_checklist)} 项",
            "试点用途": "确认字段来源、映射维度、缺口影响和替代方案，支撑样本回放与上线评估。",
        },
        "sections": _build_sections(industry_label),
        "data_readiness_checklist": readiness_checklist,
    }
    return package


def build_pilot_field_mapping_markdown(package: dict) -> str:
    lines = [f"# {package['package_title']}", ""]
    lines.extend(_rows_to_markdown("封面摘要", [{"项目": key, "内容": value} for key, value in package["summary"].items()]))
    for section_name in SECTION_NAMES:
        lines.extend(_rows_to_markdown(section_name, package["sections"][section_name]))
    lines.extend(_rows_to_markdown("试点数据准备清单", package["data_readiness_checklist"]))
    return "\n".join(lines).strip() + "\n"


def _dominant_dimensions(weights: dict) -> str:
    if not weights:
        return "外部风险、内部履约、财务信用、关联与经营稳定"
    sorted_items = sorted(weights.items(), key=lambda item: item[1], reverse=True)
    return "、".join(f"{DIMENSIONS.get(key, key)} {value:.0%}" for key, value in sorted_items)


