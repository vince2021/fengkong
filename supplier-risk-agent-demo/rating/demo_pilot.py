def build_pilot_markdown(workspace: dict) -> str:
    sections = [f"# {workspace['workspace_title']}"]
    for section_name in ["试点目标", "阶段路线图", "字段清单", "样本清单", "验收指标", "风险与依赖"]:
        sections.append(f"## {section_name}")
        sections.append(_rows_to_markdown(workspace[section_name]))
    return "\n\n".join(sections)


def _rows_to_markdown(rows: list[dict]) -> str:
    if not rows:
        return "暂无内容"
    headers = list(rows[0].keys())
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join(["---"] * len(headers)) + " |",
    ]
    for row in rows:
        lines.append("| " + " | ".join(_markdown_cell(row.get(header, "")) for header in headers) + " |")
    return "\n".join(lines)


def _markdown_cell(value) -> str:
    return str(value).replace("|", "\\|").replace("\n", "<br>")


def _join(items: list[str]) -> str:
    return "、".join(items)


def _result_text(flow: dict) -> str:
    summary = flow["summary"]
    return f"{summary['最终评级']} / {summary['准入策略']} / {summary['风险分层']}"
