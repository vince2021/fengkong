def build_demo_readiness_checklist(route: dict) -> dict:
    return {
        "industry_label": route["industry_label"],
        "model_name": route["model_name"],
        "model_version": route["model_version"],
        "route_steps": len(route["steps"]),
        "opening": f"面向{route['industry_label']}场景，演示前先确认角色、样本、数据口径、控场策略和试点承接。",
        "sections": READINESS_SECTIONS,
    }


def build_demo_readiness_markdown(readiness: dict) -> str:
    lines = [
        "# 面客演示准备检查清单",
        "",
        f"- 行业：{readiness['industry_label']}",
        f"- 模型名称：{readiness['model_name']}",
        f"- 模型版本：{readiness['model_version']}",
        f"- 路线步骤：{readiness['route_steps']}",
        f"- 准备目标：{readiness['opening']}",
        "",
    ]
    for section in readiness["sections"]:
        lines.extend(["", f"## {section['section']}", ""])
        for item in section["items"]:
            lines.extend(
                [
                    f"### {item['检查项']}",
                    "",
                    f"- 检查项：{item['检查项']}",
                    f"- 为什么重要：{item['为什么重要']}",
                    f"- 风险兜底：{item['风险兜底']}",
                    f"- 负责人：{item['负责人']}",
                    "",
                ]
            )
    return "\n".join(lines).strip() + "\n"
